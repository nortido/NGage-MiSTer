static uint32_t svc_map(uint32_t a)
{
    if (a < 0x700000u)
        return a;
    if (a < 0x800000u)
        return a - 0x700000u + 0x1300000u;
    if (a >= 0x2000000u && a < 0x2400000u)
        return a - 0x2000000u + 0x700000u;
    if (a >= 0x4000000u && a < 0x4800000u)
        return a - 0x4000000u + 0xB00000u;
    return SVC_UNMAPPED;
}

static int svc_chain(const uint8_t *f, size_t len, size_t o, uint32_t min, uint8_t *out, uint32_t *pos)
{
    if (len < o)
        return NGL_SVCROM_E_TRUNC;
    while (o < len) {
        const uint8_t *h = f + o;
        uint32_t a, l;
        size_t left;

        if (h[0] != SVC_LEAD)
            return NGL_SVCROM_E_BLOCK;
        left = len - o;
        if (left < SVC_HDR)
            return NGL_SVCROM_E_TRUNC;
        a = (uint32_t)h[1] << 24 | (uint32_t)h[2] << 16 | (uint32_t)h[3] << 8 | h[4];
        l = (uint32_t)h[6] << 16 | (uint32_t)h[7] << 8 | h[8];
        if (l > left - SVC_HDR)
            return NGL_SVCROM_E_TRUNC;
        if (a >= min) {
            uint32_t t = svc_map(a);

            if (t == SVC_UNMAPPED || l > NGL_SVCROM_SIZE - t)
                return NGL_SVCROM_E_ADDR;
            if (t < *pos)
                return NGL_SVCROM_E_ORDER;
            memcpy(out + t, h + SVC_HDR, l);
            *pos = t + l;
        }
        o += SVC_HDR + l;
    }
    return NGL_SVCROM_OK;
}

int ngl_svcrom_check(const uint8_t *b, size_t len, int id)
{
    size_t want;
    uint32_t crc;

    switch (id) {
    case NGL_SVCROM_3C1:
        want = NGL_SVCROM_3C1_LEN;
        crc = NGL_SVCROM_CRC_3C1;
        break;
    case NGL_SVCROM_326:
        want = NGL_SVCROM_326_LEN;
        crc = NGL_SVCROM_CRC_326;
        break;
    case NGL_SVCROM_OUT:
        want = NGL_SVCROM_SIZE;
        crc = NGL_SVCROM_CRC_OUT;
        break;
    default:
        return NGL_SVCROM_E_SIZE;
    }
    if (len != want)
        return NGL_SVCROM_E_SIZE;
    return ngl_sav_crc32(b, len) == crc ? NGL_SVCROM_OK : NGL_SVCROM_E_CRC;
}

int ngl_svcrom_build(const uint8_t *c1, size_t c1len, const uint8_t *s26, size_t s26len,
                     uint8_t *out, size_t cap)
{
    uint32_t pos = 0;
    int rc;

    if (cap != NGL_SVCROM_SIZE)
        return NGL_SVCROM_E_SIZE;
    memset(out, 0xFF, cap);
    rc = svc_chain(c1, c1len, SVC_C1_START, 0, out, &pos);
    if (rc)
        return rc;
    rc = svc_chain(s26, s26len, SVC_S26_START, SVC_S26_MIN, out, &pos);
    if (rc)
        return rc;
    for (size_t i = 0; i < sizeof svc_runs / sizeof svc_runs[0]; i++)
        memcpy(out + svc_runs[i].off, svc_bytes + svc_runs[i].at, svc_runs[i].len);
    return NGL_SVCROM_OK;
}

const char *ngl_svcrom_strerror(int err)
{
    switch (err) {
    case NGL_SVCROM_OK:
        return "ok";
    case NGL_SVCROM_E_SIZE:
        return "wrong size";
    case NGL_SVCROM_E_CRC:
        return "wrong crc";
    case NGL_SVCROM_E_BLOCK:
        return "bad block";
    case NGL_SVCROM_E_ADDR:
        return "bad address";
    case NGL_SVCROM_E_ORDER:
        return "blocks out of order";
    case NGL_SVCROM_E_TRUNC:
        return "truncated file";
    default:
        return "unknown error";
    }
}
