set -eu
here=$(cd "$(dirname "$0")" && pwd)
cc=${NGH_CC:-arm-none-eabi-gcc}
tb=$(dirname "$(command -v "$cc")")
objcopy=$tb/arm-none-eabi-objcopy
nm=$tb/arm-none-eabi-nm
out=${NGH_NOS_OUT:-$(cd "$here/.." && pwd)/build/nos}
flags="-marm -march=armv4t -Os -ffreestanding -fno-builtin -nostdlib -fno-common -fno-pic -fno-tree-loop-distribute-patterns -fstack-usage -Wall -Wextra -Werror"

die() { echo "build_nos: $*" >&2; exit 1; }
md5file() { if command -v md5sum >/dev/null 2>&1; then md5sum < "$1" | awk '{print $1}'; else md5 -q "$1"; fi; }
words() { xxd -e -g4 -c4 "$1" | awk '{print $2}'; }
romwords() { xxd -s "$(($1))" -l "$2" -e -g4 -c4 "$rom" | awk '{print $2}'; }

rom=""
dst=""
while [ $# -gt 0 ]; do
    case $1 in
        --rom) rom=${2:-};;
        --out) dst=${2:-};;
        *) die "usage: build_nos.sh --rom ROM --out FILE";;
    esac
    shift 2 || die "usage: build_nos.sh --rom ROM --out FILE"
done
[ -n "$rom" ] && [ -n "$dst" ] || die "usage: build_nos.sh --rom ROM --out FILE"
[ -f "$rom" ] || die "$rom not found"

mkdir -p "$out"
printf '#include "nos_isi.h"\nchar o_size[sizeof(struct nos_ch)];\n' > "$out/off.c"
# shellcheck disable=SC2086
"$cc" $flags -I "$here" -c -o "$out/off.o" "$out/off.c"
chsize=$("$nm" -S "$out/off.o" | awk '$4 == "o_size" { print "0x" $2 }')
[ -n "$chsize" ] || die "no struct nos_ch size"
rm -f "$out/off.su"

# shellcheck disable=SC2086
"$cc" $flags -c -o "$out/nos_isi.o" "$here/nos_isi.c"
# shellcheck disable=SC2086
"$cc" $flags -DNOS_CH_SIZE="$chsize" -c -o "$out/nos_glue.o" "$here/nos_glue.S"
# shellcheck disable=SC2086
"$cc" $flags -static -Wl,-T,"$here/nos.ld" -Wl,--build-id=none -Wl,--no-warn-rwx-segments \
    -o "$out/nos.elf" "$out/nos_glue.o" "$out/nos_isi.o"
"$objcopy" -O binary -j .text "$out/nos.elf" "$out/nos.bin"
"$objcopy" -O binary -j .exp4 "$out/nos.elf" "$out/exp4.bin"
"$objcopy" -O binary -j .exp6 "$out/nos.elf" "$out/exp6.bin"
"$objcopy" -O binary -j .objsize "$out/nos.elf" "$out/size.bin"
boff=$((0x511b6000 - 0x50000000))
blen=$(wc -c < "$out/nos.bin" | tr -d ' ')

[ -z "$(romwords "$boff" "$blen" | grep -v -x ffffffff)" ] || die "$rom: the blob range is not erased flash"

{
    echo "# NOS ISI model for nosdriver (hps/guest), generated by hps/guest/build_nos.sh against base.rom: do not edit"
    echo "# gcc $("$cc" --version | head -n 1)"
    echo "# flags $flags"
    printf '# blob %08x+%x md5 %s\n' "$boff" "$blen" "$(md5file "$out/nos.bin")"
    printf '011b4028 %s %s\n' "$(romwords 0x11b4028 4)" "$(words "$out/exp4.bin")"
    printf '011b4030 %s %s\n' "$(romwords 0x11b4030 4)" "$(words "$out/exp6.bin")"
    printf '011b413c %s %s\n' "$(romwords 0x11b413c 4)" "$(words "$out/size.bin")"
    paste -d ' ' <(romwords "$boff" "$blen") <(words "$out/nos.bin") | awk -v b="$boff" '{ printf "%08x %s\n", b + 4 * (NR - 1), $0 }'
} > "$out/patch_nos.txt"
cp "$out/patch_nos.txt" "$dst"
