set -eu
here=$(cd "$(dirname "$0")" && pwd)
cc=${NGH_CC:-arm-none-eabi-gcc}
tb=$(dirname "$(command -v "$cc")")
objcopy=$tb/arm-none-eabi-objcopy
nm=$tb/arm-none-eabi-nm
out=${NGH_BT_OUT:-$(cd "$here/.." && pwd)/build/bt}
flags="-marm -march=armv4t -Os -ffreestanding -fno-builtin -nostdlib -fno-common -fno-pic -fno-tree-loop-distribute-patterns -fstack-usage -Wall -Wextra -Werror"

die() { echo "build_bt: $*" >&2; exit 1; }
md5file() { if command -v md5sum >/dev/null 2>&1; then md5sum < "$1" | awk '{print $1}'; else md5 -q "$1"; fi; }
words() { xxd -e -g4 -c4 "$1" | awk '{print $2}'; }
romwords() { xxd -s "$(($1))" -l "$2" -e -g4 -c4 "$rom" | awk '{print $2}'; }

rom=""
dst=""
while [ $# -gt 0 ]; do
    case $1 in
        --rom) rom=${2:-};;
        --out) dst=${2:-};;
        *) die "usage: build_bt.sh --rom ROM --out FILE";;
    esac
    shift 2 || die "usage: build_bt.sh --rom ROM --out FILE"
done
[ -n "$rom" ] && [ -n "$dst" ] || die "usage: build_bt.sh --rom ROM --out FILE"
[ -f "$rom" ] || die "$rom not found"

mkdir -p "$out"
printf '#include "bt_hci.h"\nchar o_size[sizeof(struct bt_st)];\nchar o_out[__builtin_offsetof(struct bt_st, out)];\nchar o_full[__builtin_offsetof(struct bt_st, ring_full)];\n' > "$out/off.c"
# shellcheck disable=SC2086
"$cc" $flags -I "$here" -c -o "$out/off.o" "$out/off.c"
off() { "$nm" -S "$out/off.o" | awk -v s="$1" '$4 == s { print "0x" $2 }'; }
defs="-DBT_ST_SIZE=$(off o_size) -DBT_ST_OUT=$(off o_out) -DBT_ST_FULL=$(off o_full)"
rm -f "$out/off.su"

# shellcheck disable=SC2086
"$cc" $flags -c -o "$out/bt_hci.o" "$here/bt_hci.c"
# shellcheck disable=SC2086
"$cc" $flags $defs -c -o "$out/bt_glue.o" "$here/bt_glue.S"
# shellcheck disable=SC2086
"$cc" $flags -static -Wl,-T,"$here/bt.ld" -Wl,--build-id=none -Wl,--no-warn-rwx-segments \
    -o "$out/bt.elf" "$out/bt_glue.o" "$out/bt_hci.o"
"$objcopy" -O binary -j .text "$out/bt.elf" "$out/bt.bin"
"$objcopy" -O binary -j .hook "$out/bt.elf" "$out/hook.bin"
"$objcopy" -O binary -j .objsize "$out/bt.elf" "$out/size.bin"
base=$("$nm" "$out/bt.elf" | awk '$3 == "bt_glue_write" { print $1 }')
[ -n "$base" ] || die "no bt_glue_write"
boff=$((0x$base - 0x50000000))
blen=$(wc -c < "$out/bt.bin" | tr -d ' ')

[ -z "$(romwords "$boff" "$blen" | grep -v -x ffffffff)" ] || die "$rom: the blob range is not erased flash"

{
    echo "# BT HCI model for BTLDD (hps/guest), generated by hps/guest/build_bt.sh against base.rom: do not edit"
    echo "# gcc $("$cc" --version | head -n 1)"
    echo "# flags $flags"
    printf '# blob %08x+%x md5 %s\n' "$boff" "$blen" "$(md5file "$out/bt.bin")"
    paste -d ' ' <(romwords 0x3f1cd0 12) <(words "$out/hook.bin") | awk -v b=$((0x3f1cd0)) '{ printf "%08x %s\n", b + 4 * (NR - 1), $0 }'
    paste -d ' ' <(romwords 0x3f28b0 4) <(words "$out/size.bin") | awk '{ printf "003f28b0 %s\n", $0 }'
    paste -d ' ' <(romwords "$boff" "$blen") <(words "$out/bt.bin") | awk -v b="$boff" '{ printf "%08x %s\n", b + 4 * (NR - 1), $0 }'
} > "$out/patch_bt.txt"
cp "$out/patch_bt.txt" "$dst"
